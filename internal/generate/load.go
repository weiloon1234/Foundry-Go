const framework = frameworkinfo.ModulePath
const generatedHeader = "// Code generated by foundry generate; DO NOT EDIT."

type listedPackage struct {
	Dir, ImportPath, Name, Export string
	GoFiles, CgoFiles             []string
	IgnoredGoFiles                []string
	Imports, Match                []string
	Module                        *listedModule
	Error                         *struct{ Err string }
}
type source struct {
	name   string
	data   []byte
	syntax *ast.File
}
type packageInput struct {
	dir, path, name string
	// display is the module-relative directory used in diagnostics.
	display  string
	files    []source
	previous map[string][]byte
	defined  map[string]bool
	// definedAt and methods locate handwritten declarations that generated
	// symbols must not redeclare.
	definedAt  map[string]token.Pos
	methods    map[string]map[string]token.Pos
	goNames    []string
	fset       *token.FileSet
	importer   types.Importer
	types      *types.Package
	checked    *types.Package
	enumTypes  map[*types.Named]bool
	unionTypes map[*types.Named]*unionDeclaration
}

// A selected package can lack compiled exports on a fresh checkout. Analyze its
// handwritten declarations using already checked in-memory dependencies first.
// Full syntax is parsed once with module-relative names, so every diagnostic names
// the actual source path rather than an ambiguous basename.
func (g *packageGraph) loadPackage(path string) (*packageInput, error) {
	target := g.packages[path]
	absolute := target.Dir
	input := &packageInput{dir: absolute, path: target.ImportPath, name: target.Name, display: g.scope.display(absolute), fset: g.fset, previous: make(map[string][]byte), goNames: g.snapshot[absolute], importer: g}
	sort.Strings(target.GoFiles)
	declared := false
	for _, name := range target.GoFiles {
		data, err := os.ReadFile(filepath.Join(absolute, name))
		if err != nil {
			return nil, err
		}
		if bytes.HasPrefix(data, []byte(generatedHeader+"\n")) {
			input.previous[name] = data
			continue
		}
		full, err := parser.ParseFile(input.fset, input.displayName(name), data, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		declared = declared || mayDeclare(data)
		input.files = append(input.files, source{name, data, full})
	}
	for _, path := range sortedNames(g.overlay) {
		name := filepath.Base(path)
		if filepath.Dir(path) != absolute {
			continue
		}
		if slices.Contains(target.GoFiles, name) {
			return nil, fmt.Errorf("proposed file %s already exists", input.displayName(name))
		}
		full, err := parser.ParseFile(input.fset, input.displayName(name), g.overlay[path], parser.ParseComments)
		if err != nil {
			return nil, err
		}
		declared = declared || mayDeclare(g.overlay[path])
		input.files = append(input.files, source{name, g.overlay[path], full})
	}
	if !declared {
		// Without directives there is nothing to discover. The complete overlay
		// check still validates the package and supplies it to dependents.
		input.defined = make(map[string]bool)
		return input, nil
	}
	declarations, err := input.declarationFiles()
	if err != nil {
		return nil, err
	}
	config := types.Config{Importer: input.importer, IgnoreFuncBodies: true, DisableUnusedImportCheck: true}
	input.types, err = config.Check(input.path, input.fset, declarations, nil)
	if err != nil {
		return nil, fmt.Errorf("check source declarations: %w", err)
	}
	return input, nil
}

// displayName is a module-relative source or output path for diagnostics.
func (p *packageInput) displayName(name string) string {
	if p.display == "" || p.display == "." {
		return name
	}
	return p.display + "/" + name
}

// check parses generated outputs once, rejects collisions with handwritten
// declarations at their source positions, then type-checks the full overlay.
func (p *packageInput) check(outputs map[string][]byte, origins map[string]token.Position) error {
	files := make([]*ast.File, 0, len(p.files)+len(outputs))
	for _, file := range p.files {
		files = append(files, file.syntax)
	}
	names := sortedNames(outputs)
	generated := make(map[string]*ast.File, len(outputs))
	for _, name := range names {
		syntax, err := parser.ParseFile(p.fset, p.displayName(name), outputs[name], parser.ParseComments)
		if err != nil {
			return err
		}
		generated[name] = syntax
		files = append(files, syntax)
	}
	if err := p.checkGeneratedNames(generated, origins); err != nil {
		return err
	}
	config := types.Config{Importer: p.importer}
	checked, err := config.Check(p.path, p.fset, files, nil)
	if err != nil {
		return fmt.Errorf("check generated package overlay: %w", err)
	}
	p.checked = checked
	return nil
}

// mayDeclare is the byte-level prefilter for Foundry directives. It accepts
// every line-comment form directive parsing accepts, including whitespace after
// the slashes (`// foundry:model`), so a file with a declaration is never
// skipped. False positives, such as the text inside a string, only cost a parse.
func mayDeclare(data []byte) bool {
	marker := []byte("foundry:")
	for offset := 0; ; {
		index := bytes.Index(data[offset:], marker)
		if index < 0 {
			return false
		}
		start := offset + index
		for start > 0 {
			r, size := utf8.DecodeLastRune(data[:start])
			if r == '\n' || !unicode.IsSpace(r) {
				break
			}
			start -= size
		}
		if bytes.HasSuffix(data[:start], []byte("//")) {
			return true
		}
		offset += index + len(marker)
	}
}

// hasDeclarationDirective reports whether a file attaches a Foundry directive to
// a type declaration. Directive validation remains owned by discovery.
func hasDeclarationDirective(name string, data []byte) (bool, error) {
	syntax, err := parser.ParseFile(token.NewFileSet(), name, data, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return false, err
	}
	for _, decl := range syntax.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			comments := spec.(*ast.TypeSpec).Doc
			if comments == nil {
				comments = gen.Doc
			}
			if comments == nil {
				continue
			}
			for _, comment := range comments.List {
				if strings.HasPrefix(strings.TrimSpace(strings.TrimPrefix(comment.Text, "//")), "foundry:") {
					return true, nil
				}
			}
		}
	}
	return false, nil
}

func goSourceNames(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0)
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".go") {
			names = append(names, entry.Name())
		}
	}
	return names, nil
}

func sortedNames[V any](items map[string]V) []string {
	names := make([]string, 0, len(items))
	for name := range items {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
