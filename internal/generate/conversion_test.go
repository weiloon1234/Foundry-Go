func TestConversionPublicationAndRecovery(t *testing.T) {
	for _, complete := range []bool{false, true} {
		t.Run(map[bool]string{false: "interrupted", true: "completed"}[complete], func(t *testing.T) {
			dir := t.TempDir()
			before := []byte("package sample\ntype Model struct{ ID int }\n")
			after := []byte("package sample\n//foundry:model table=models var=Models key=ID\ntype Model struct{ ID int }\n")
			write(t, dir, "model.go", string(before))
			old, err := readFile(filepath.Join(dir, "model.go"))
			if err != nil {
				t.Fatal(err)
			}
			plan := writePlan{conversion: true, guards: []string{"."}, before: map[string]oldFile{"model.go": old, "model_foundry.gen.go": {}}, changes: map[string][]byte{"model.go": after, "model_foundry.gen.go": []byte("// Code generated by foundry generate; DO NOT EDIT.\npackage sample\n")}}
			if err := prepareStaging(dir, plan); err != nil {
				t.Fatal(err)
			}
			write(t, dir, "model.go", string(after))
			if complete {
				write(t, dir, "model_foundry.gen.go", string(plan.changes["model_foundry.gen.go"]))
			}
			result, err := Recover(t.Context(), dir)
			if err != nil {
				t.Fatal(err)
			}
			if complete != result.Kept || complete == result.RolledBack {
				t.Fatalf("recovery: %+v", result)
			}
			got, err := os.ReadFile(filepath.Join(dir, "model.go"))
			if err != nil {
				t.Fatal(err)
			}
			want := before
			if complete {
				want = after
			}
			if !bytes.Equal(got, want) {
				t.Fatal("source recovery differs")
			}
		})
	}
}
func TestConversionPublicationRejectsChangedAndUnsafeSources(t *testing.T) {
	for _, name := range []string{"../model.go", ".env.go", "model_test.go", "model.go"} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			write(t, dir, "model.go", "package sample\n")
			err := PublishConversion(context.Background(), dir, []ConversionFile{{Name: name, Before: []byte("stale"), After: []byte("package sample\n")}})
			if err == nil {
				t.Fatal("unsafe or stale replacement accepted")
			}
		})
	}
}

func TestConversionValidationOwnsFilesystemDiagnostic(t *testing.T) {
	err := ValidateConversion(t.Context(), filepath.Join(t.TempDir(), "missing"), nil)
	message, ok := safeerror.OwnedMessage(err)
	if !ok || !strings.Contains(message, "no such file or directory") {
		t.Fatalf("lost owned filesystem diagnostic: %v", err)
	}
}
