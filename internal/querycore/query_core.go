package querycore

import (
	"context"

	"github.com/weiloon1234/Foundry-Go/fault"
	"github.com/weiloon1234/Foundry-Go/internal/sqlname"
	"github.com/weiloon1234/Foundry-Go/value"
)

// queryCore owns model-independent builder state and planning. Public adapters
// check concrete owner/value types before lowering into the existing SQL AST.
// Values are immutable: every operation extending a slice makes an owned copy.
type QueryCore struct {
	Table      string
	Predicates []Expression
	Orders     []QueryOrder
	Limit      value.Optional[int]
	Offset     int

	SoftDeleteScope SoftDeleteScope
	// Global scope options: removed scopes, all scopes removed, and the
	// context that resolves context scopes (see WithScopeContext).
	WithoutScopes []GlobalScopeName
	AllScopesOff  bool
	ScopeContext  context.Context
	// skipModelHooks acknowledges hook-free set-based writes only.
	SkipModelHooks bool
	// distinctOnKey is set only by one-of-many relation loading.
	DistinctOnKey *FieldRef
	Model         *ModelDefinition
}

// modelDefinition contains immutable SQL metadata. Hydration, field getters and
// lifecycle callbacks remain on Definition[M]; no service or model is boxed.
type ModelDefinition struct {
	Sensitive      map[string]bool
	Table, Primary string
	Columns        []Column
	Timestamps     *TimestampColumns
	SoftDelete     *SoftDeleteColumn
	GlobalScopes   []ScopeDefinition
	ScopeSource    *LazyScopes
}

func (d ModelDefinition) ValidateColumns(hasDecoder bool) (map[string]bool, error) {
	if !sqlname.Table(d.Table) || !sqlname.Valid(d.Primary) || len(d.Columns) == 0 || len(d.Columns) > MaxExpressionNodes || !hasDecoder {
		return nil, fault.New(fault.Invalid, "invalid model query definition")
	}
	seen := make(map[string]bool, len(d.Columns))
	encrypted, assignedKey := false, false
	for _, column := range d.Columns {
		if !sqlname.Valid(column.Name) || seen[column.Name] || (column.Name == d.Primary && (column.Nullable || column.Encrypted)) {
			return nil, fault.New(fault.Invalid, "invalid or repeated model column")
		}
		seen[column.Name] = true
		encrypted = encrypted || column.Encrypted
		assignedKey = assignedKey || column.Name == d.Primary && !column.DatabaseDefault
	}
	// An encrypted value is bound to its row's primary key, which must therefore
	// be known before the insert rather than generated by the database.
	if encrypted && !assignedKey {
		return nil, fault.New(fault.Invalid, "encrypted model fields require an application-assigned primary key")
	}
	if !seen[d.Primary] {
		return nil, fault.New(fault.Invalid, "model primary column is not declared")
	}

	return seen, nil
}

type QueryOrder struct {
	Field      FieldRef
	Computed   *ComputedOrder
	Descending bool
	Nulls      NullPlacement
}

func (o QueryOrder) Value() ValueExpression {
	if o.Computed != nil {
		if o.Field != (FieldRef{}) {
			return ParameterNode{Err: fault.New(fault.Invalid, "ambiguous row ordering")}
		}
		return o.Computed.Expression
	}
	return o.Field
}

func (q QueryCore) Validate() error {
	if err := q.ValidateSoftDeleteScope(); err != nil {
		return err
	}
	if err := q.ValidateScopeOptions(); err != nil {
		return err
	}
	if !sqlname.Table(q.Table) {
		return fault.New(fault.Invalid, "query has an invalid table declaration")
	}
	if limit, set := q.Limit.Get(); (set && limit < 0) || q.Offset < 0 {
		return fault.New(fault.Invalid, "query limit and offset cannot be negative")
	}
	if len(q.Orders) > MaxExpressionNodes {
		return fault.New(fault.Invalid, "query ordering exceeds its resource bound")
	}
	nodes := 0
	for _, p := range q.EffectivePredicates() {
		if err := ValidateExpression(p, q.Table, 0, &nodes); err != nil {
			return err
		}
	}
	for _, order := range q.Orders {
		if err := ValidateRowValue(order.Value(), func(f FieldRef) error { return f.Validate(q.Table) }, 0, &nodes); err != nil {
			return err
		}
	}
	return nil
}

func (q QueryCore) StableOrder() (QueryCore, error) {
	if q.Model == nil {
		return QueryCore{}, fault.New(fault.Invalid, "ordered model reads require model metadata")
	}
	seen := make(map[string]bool, len(q.Orders))
	for _, order := range q.Orders {
		// A computed key does not prove primary-key uniqueness. Preserve it and
		// append the actual primary field as the final tie-breaker below.
		if order.Computed != nil {
			continue
		}
		if seen[order.Field.Column] {
			return QueryCore{}, fault.New(fault.Invalid, "ordered model reads cannot repeat an ordered column")
		}
		seen[order.Field.Column] = true
	}
	if !seen[q.Model.Primary] {
		q.Orders = append(append([]QueryOrder(nil), q.Orders...), QueryOrder{Field: FieldRef{q.Table, q.Model.Primary}})
	}
	return q, nil
}

func (q QueryCore) CompileModel(kind ReadKind, selections []SelectItem) (Statement, error) {
	// SELECT owns its source-column maps; the mutation column map is unused.
	c := Compiler{ScopeContext: q.ScopeContext}
	c.BeginStatement(q.ScopeContext)
	if kind == ReadExists {
		if n, set := q.Limit.Get(); !set || n > 1 {
			q.Limit = value.Set(1)
		}
	}
	node := q.ModelSelect(selections)
	if kind != ReadModels {
		node.Selections = nil
	}
	if kind == ReadCount {
		node = CountNode(node)
	}
	statement, err := c.CompileSelect(node)
	if err != nil {
		return Statement{}, err
	}
	prefix, suffix := ReadEnvelope(kind)
	statement = prefix + statement + suffix
	return c.Statement(statement), nil
}

func (q QueryCore) ModelSelect(selections []SelectItem) SelectNode {
	node := SelectNode{Source: q.Model.Source(q.Table, ""), Selections: selections, Predicates: q.EffectivePredicates(), Orders: OrderNodes(q.Orders), Limit: q.Limit, Offset: q.Offset}
	if q.DistinctOnKey != nil {
		// One-of-many loading keeps the first row per relation key.
		node.Distinct = DistinctSpec{Kind: DistinctOn, Keys: []ValueExpression{*q.DistinctOnKey}}
		node.Orders = append([]OrderNode{{Expression: *q.DistinctOnKey}}, node.Orders...)
	}
	return node
}

func (q QueryCore) WriteCompiler(kind MutationKind, requirePrimary, hasRelations bool) (Compiler, error) {
	if q.Model == nil {
		return Compiler{}, fault.New(fault.Invalid, "model mutation requires generated metadata")
	}
	if kind > DeleteModel {
		return Compiler{}, fault.New(fault.Invalid, "invalid model mutation kind")
	}
	if len(q.Orders) != 0 || q.Limit.IsSet() || q.Offset != 0 {
		return Compiler{}, fault.New(fault.Invalid, "model writes do not accept ordering or pagination")
	}
	if hasRelations {
		return Compiler{}, fault.New(fault.Invalid, "model writes cannot include eager-loading options")
	}
	if kind == InsertModel && (len(q.Predicates) != 0 || q.SoftDeleteScope != ActiveRecords) {
		return Compiler{}, fault.New(fault.Invalid, "model creation does not accept query predicates")
	}
	if requirePrimary && kind != InsertModel && !HasPrimaryEquality(q.Predicates, q.Model.Primary) {
		return Compiler{}, fault.New(fault.Invalid, "single-model write requires a primary-key equality predicate")
	}
	c := NewCompiler(q.Model.Columns)
	c.Sources = map[string]map[string]Column{q.Table: c.Columns}
	c.ScopeContext = q.ScopeContext
	return c, nil
}

func (q QueryCore) RequireInsertFields(present func(string) bool) error {
	for _, column := range q.Model.Columns {
		if !present(column.Name) && !column.Nullable && !column.DatabaseDefault {
			return fault.New(fault.Missing, "model creation requires field "+column.Name)
		}
	}
	return nil
}

func CompileRead(node SelectNode, scopeContext context.Context, transaction bool, err error, hasDecoder bool) (Statement, error) {
	if err != nil {
		return Statement{}, err
	}
	if !hasDecoder {
		return Statement{}, fault.New(fault.Invalid, "query requires a complete result decoder")
	}
	c := Compiler{AllowLocks: transaction, ScopeContext: scopeContext}
	c.BeginStatement(scopeContext)
	sql, err := c.CompileSelect(node)
	if err != nil {
		return Statement{}, err
	}
	return c.Statement(sql), nil
}

// ReadEnvelope owns scalar result wrappers and their internal output alias.
func ReadEnvelope(kind ReadKind) (string, string) {
	switch kind {
	case ReadCount:
		return `SELECT COUNT(*) FROM (`, `) AS "foundry_count"`
	case ReadExists:
		return "SELECT EXISTS(", ")"
	default:
		return "", ""
	}
}
