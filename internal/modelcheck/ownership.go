package modelcheck

import (
	"bytes"
	"encoding/json"
	"go/ast"
	"os"
	"path/filepath"
	"strings"
	"sync"

	"github.com/weiloon1234/Foundry-Go/internal/frameworkinfo"
)

const generatedHeader = "// Code generated by foundry generate; DO NOT EDIT."

type manifestData struct {
	exists bool
	files  map[string]bool
}

type manifestCache struct {
	mu        sync.RWMutex
	manifests map[string]*manifestData
}

func newManifestCache() *manifestCache {
	return &manifestCache{manifests: make(map[string]*manifestData)}
}

func (c *manifestCache) get(dir string) *manifestData {
	c.mu.RLock()
	cached, ok := c.manifests[dir]
	c.mu.RUnlock()
	if ok {
		return cached
	}

	c.mu.Lock()
	defer c.mu.Unlock()
	if cached, ok = c.manifests[dir]; ok {
		return cached
	}

	data := &manifestData{files: make(map[string]bool)}
	manifestPath := filepath.Join(dir, frameworkinfo.GenerationManifest)
	raw, err := os.ReadFile(manifestPath)
	if err == nil {
		var m struct {
			Version int               `json:"version"`
			Files   map[string]string `json:"files"`
		}
		if json.Unmarshal(raw, &m) == nil && m.Files != nil {
			data.exists = true
			for k := range m.Files {
				data.files[k] = true
			}
		}
	}
	c.manifests[dir] = data
	return data
}

// isGeneratedOwned reports whether a file is owned by the generator,
// requiring both the generation manifest (.foundry-gen.json) and the
// generated header comment.
func (a *Analysis) isGeneratedOwned(filePath string, file *ast.File) bool {
	if !hasGeneratedHeader(filePath, file) {
		return false
	}
	dir := filepath.Dir(filePath)
	manifest := a.manifestCache.get(dir)
	if !manifest.exists {
		return false
	}
	base := filepath.Base(filePath)
	return manifest.files[base]
}

func hasGeneratedHeader(filePath string, file *ast.File) bool {
	if file != nil {
		for _, cg := range file.Comments {
			for _, c := range cg.List {
				text := strings.TrimSpace(c.Text)
				if strings.HasPrefix(text, generatedHeader) {
					return true
				}
			}
		}
	}
	if filePath != "" {
		data, err := os.ReadFile(filePath)
		if err == nil {
			return bytes.HasPrefix(bytes.TrimSpace(data), []byte(generatedHeader))
		}
	}
	return false
}
