// SurfaceFile is the recorded exported API of the importable packages, relative
// to the framework root. ReleaseSurfaceFile and ReleaseLedgerFile record the
// same two inputs as of the last release tag; the release step replaces them.
const (
	SurfaceFile        = "internal/retirement/exported-surface.txt"
	ReleaseSurfaceFile = "internal/retirement/release/exported-surface.txt"
	ReleaseLedgerFile  = "internal/retirement/release/retired-names.txt"
	LedgerFile         = "internal/retirement/denied.json"
	// PackageEntry is the ledger name that retires a whole package. It is a Go
	// keyword, so it can never collide with an identifier of the package.
	PackageEntry = "package"
)

const surfaceHeader = `# Exported API of the framework's importable packages: every non-internal,
# non-main package of the root module, type-checked for linux/amd64,
# darwin/arm64 and windows/amd64 with cgo off (the union of the three).
# Columns: package, kind, name. A name is Func, Type, Type.Method or Type.Field;
# kind is func, type, alias, const, var, method, method* (pointer receiver) or field.
# Generated by internal/cmd/exportsurface (make generate); do not edit.
`

// The supported build configurations. Platform files declare no exported API
// today; the union keeps that true if one ever does.
var surfaceConfigs = []struct{ goos, goarch string }{
	{"linux", "amd64"}, {"darwin", "arm64"}, {"windows", "amd64"},
}

// ReleaseSurface is the inventory as recorded at a release tag.
func ReleaseSurface(current []byte, tag string) []byte {
	return append([]byte("# Recorded at release "+tag+".\n"), current...)
}

// Surface computes the recorded inventory of root as the file's bytes.
func Surface(root string) ([]byte, error) {
	root, err := filepath.Abs(root)
	if err != nil {
		return nil, err
	}
	dirs, err := surfaceDirs(root)
	if err != nil {
		return nil, err
	}
	var contexts []build.Context
	for _, config := range surfaceConfigs {
		ctx := build.Default
		ctx.GOOS, ctx.GOARCH, ctx.CgoEnabled = config.goos, config.goarch, false
		contexts = append(contexts, ctx)
	}
	external := make(map[string]bool)
	for _, ctx := range contexts {
		if err := collectExternalImports(root, ctx, dirs, external); err != nil {
			return nil, err
		}
	}
	fset := token.NewFileSet()
	imports := types.Importer(noImports{})
	if len(external) != 0 {
		imports, err = exportImporter(fset, root, sortedKeys(external))
		if err != nil {
			return nil, safeerror.Prefix(root+": resolve surface imports", err)
		}
	}
	lines := make(map[string]bool)
	for _, ctx := range contexts {
		loader := &surfaceLoader{fset: fset, root: root, ctx: ctx, external: imports, packages: make(map[string]*types.Package), loading: make(map[string]bool)}
		for _, dir := range dirs {
			if strings.Contains("/"+dir+"/", "/internal/") {
				continue
			}
			pkg, err := loader.load(dir)
			if err != nil {
				return nil, err
			}
			if pkg == nil || pkg.Name() == "main" {
				continue
			}
			recordSurface(pkg, dir, lines)
		}
	}
	var out strings.Builder
	out.WriteString(surfaceHeader)
	for _, line := range sortedKeys(lines) {
		out.WriteString(line + "\n")
	}
	return []byte(out.String()), nil
}

// surfaceDirs lists the directories of the root module that hold Go files,
// relative to root, skipping nested modules, test data and tooling trees.
func surfaceDirs(root string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if !d.IsDir() {
			return nil
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		relative = filepath.ToSlash(relative)
		switch d.Name() {
		case ".cache", ".git", ".github", ".agents", "node_modules", "testdata", "tests", "tools":
			if relative != "." {
				return filepath.SkipDir
			}
		}
		if relative != "." {
			if _, err := os.Stat(filepath.Join(path, "go.mod")); err == nil {
				return filepath.SkipDir
			}
		}
		entries, err := os.ReadDir(path)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".go") {
				dirs = append(dirs, relative)
				break
			}
		}
		return nil
	})
	return dirs, err
}

func surfaceImportPath(dir string) string {
	if dir == "." {
		return strings.TrimSuffix(framework, "/")
	}
	return framework + dir
}

// collectExternalImports adds every import of the framework's packages that the
// framework itself does not own, as one configuration selects their files.
func collectExternalImports(root string, ctx build.Context, dirs []string, external map[string]bool) error {
	for _, dir := range dirs {
		pkg, err := ctx.ImportDir(filepath.Join(root, filepath.FromSlash(dir)), 0)
		if err != nil {
			if _, none := err.(*build.NoGoError); none {
				continue
			}
			return safeerror.Prefix(dir+": list package files", err)
		}
		for _, imported := range pkg.Imports {
			if imported != "unsafe" && imported != "C" && !strings.HasPrefix(imported, framework) && imported+"/" != framework {
				external[imported] = true
			}
		}
	}
	return nil
}

// noImports serves a framework without imports outside itself.
type noImports struct{}

func (noImports) Import(path string) (*types.Package, error) {
	return nil, safeerror.New(fmt.Sprintf("package %s is not an import of the framework", path))
}

// surfaceLoader type-checks framework packages from source for one build
// configuration. Function bodies are skipped: only declarations matter.
type surfaceLoader struct {
	fset     *token.FileSet
	root     string
	ctx      build.Context
	external types.Importer
	packages map[string]*types.Package
	loading  map[string]bool
}

func (l *surfaceLoader) Import(path string) (*types.Package, error) {
	if path == "unsafe" {
		return types.Unsafe, nil
	}
	dir := ""
	switch {
	case path+"/" == framework:
		dir = "."
	case strings.HasPrefix(path, framework):
		dir = strings.TrimPrefix(path, framework)
	default:
		return l.external.Import(path)
	}
	pkg, err := l.load(dir)
	if err != nil {
		return nil, err
	}
	if pkg == nil {
		return nil, safeerror.New(fmt.Sprintf("%s has no Go files for %s/%s", path, l.ctx.GOOS, l.ctx.GOARCH))
	}
	return pkg, nil
}

// load returns nil, without an error, for a directory with no files in the
// loader's configuration.
func (l *surfaceLoader) load(dir string) (*types.Package, error) {
	if pkg, ok := l.packages[dir]; ok {
		return pkg, nil
	}
	if l.loading[dir] {
		return nil, safeerror.New(fmt.Sprintf("import cycle through %s", dir))
	}
	l.loading[dir] = true
	defer delete(l.loading, dir)
	abs := filepath.Join(l.root, filepath.FromSlash(dir))
	found, err := l.ctx.ImportDir(abs, 0)
	if err != nil {
		if _, none := err.(*build.NoGoError); none {
			l.packages[dir] = nil
			return nil, nil
		}
		return nil, safeerror.Prefix(dir+": list package files", err)
	}
	var files []*ast.File
	for _, name := range found.GoFiles {
		file, err := parser.ParseFile(l.fset, filepath.Join(abs, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		files = append(files, file)
	}
	config := types.Config{Importer: l, IgnoreFuncBodies: true, FakeImportC: true, Error: func(error) {}}
	pkg, _ := config.Check(surfaceImportPath(dir), l.fset, files, nil)
	if pkg == nil {
		return nil, safeerror.New(fmt.Sprintf("%s: no scope for surface check", dir))
	}
	l.packages[dir] = pkg
	return pkg, nil
}

func recordSurface(pkg *types.Package, dir string, lines map[string]bool) {
	add := func(kind, name string) {
		lines[dir+"\t"+kind+"\t"+name] = true
	}
	for _, name := range pkg.Scope().Names() {
		obj := pkg.Scope().Lookup(name)
		if !obj.Exported() {
			continue
		}
		switch obj := obj.(type) {
		case *types.Func:
			add("func", name)
		case *types.Const:
			add("const", name)
		case *types.Var:
			add("var", name)
		case *types.TypeName:
			if obj.IsAlias() {
				add("alias", name)
				continue
			}
			add("type", name)
			named, ok := obj.Type().(*types.Named)
			if !ok {
				continue
			}
			for i := 0; i < named.NumMethods(); i++ {
				method := named.Method(i)
				if !method.Exported() {
					continue
				}
				kind := "method"
				if recv := method.Type().(*types.Signature).Recv(); recv != nil {
					if _, pointer := recv.Type().(*types.Pointer); pointer {
						kind = "method*"
					}
				}
				add(kind, name+"."+method.Name())
			}
			switch under := named.Underlying().(type) {
			case *types.Struct:
				for i := 0; i < under.NumFields(); i++ {
					if field := under.Field(i); field.Exported() {
						add("field", name+"."+field.Name())
					}
				}
			case *types.Interface:
				for i := 0; i < under.NumMethods(); i++ {
					if method := under.Method(i); method.Exported() {
						add("method", name+"."+method.Name())
					}
				}
			}
		}
	}
}

// surfaceEntry is one recorded identifier; kind is informational.
type surfaceEntry struct{ pkg, kind, name string }

func parseSurface(data []byte, source string) ([]surfaceEntry, error) {
	var entries []surfaceEntry
	for i, line := range strings.Split(string(data), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 3 {
			return nil, safeerror.New(source + ":" + strconv.Itoa(i+1) + ": want package, kind and name separated by tabs; run go run ./internal/cmd/exportsurface to regenerate")
		}
		entries = append(entries, surfaceEntry{fields[0], fields[1], fields[2]})
	}
	return entries, nil
}

// ledgerNames maps each package to its retired names.
func ledgerNames(entries map[string][]retiredDeclaration) map[string]map[string]bool {
	result := make(map[string]map[string]bool, len(entries))
	for pkg, members := range entries {
		names := make(map[string]bool, len(members))
		for _, member := range members {
			names[member.Name] = true
		}
		result[pkg] = names
	}
	return result
}

// RemovedWithoutEntry names every identifier recorded in the previous release
// that the current inventory no longer has and the ledger does not retire. A
// removed package is one entry; a removed type covers its members; a member of
// a type that still exists needs its own entry.
func RemovedWithoutEntry(previous, current []byte, ledger map[string][]retiredDeclaration) ([]string, error) {
	before, err := parseSurface(previous, ReleaseSurfaceFile)
	if err != nil {
		return nil, err
	}
	after, err := parseSurface(current, SurfaceFile)
	if err != nil {
		return nil, err
	}
	have := make(map[string]bool, len(after))
	packages := make(map[string]bool)
	for _, entry := range after {
		have[entry.pkg+"\t"+entry.name] = true
		packages[entry.pkg] = true
	}
	retired := ledgerNames(ledger)
	var missing []string
	reportedPackage := make(map[string]bool)
	for _, entry := range before {
		if have[entry.pkg+"\t"+entry.name] {
			continue
		}
		if !packages[entry.pkg] {
			if !retired[entry.pkg][PackageEntry] && !reportedPackage[entry.pkg] {
				reportedPackage[entry.pkg] = true
				missing = append(missing, fmt.Sprintf("%s: package %s was removed since the previous release; add {\"name\": %q} with its replacement (or \"noReplacement\": true) under %q in %s", LedgerFile, entry.pkg, PackageEntry, entry.pkg, LedgerFile))
			}
			continue
		}
		if retired[entry.pkg][entry.name] {
			continue
		}
		if owner, _, member := strings.Cut(entry.name, "."); member && !have[entry.pkg+"\t"+owner] {
			// A removed owner is covered by its own entry, or reported itself.
			continue
		}
		missing = append(missing, fmt.Sprintf("%s: %s.%s (%s) was removed since the previous release; add it to %s under %q with its replacement (or \"noReplacement\": true)", LedgerFile, entry.pkg, entry.name, entry.kind, LedgerFile, entry.pkg))
	}
	sort.Strings(missing)
	return missing, nil
}

// CheckRemovals compares the recorded inventories and ledgers of the previous
// release and the current tree, and refuses a ledger that lost an entry.
func CheckRemovals(root string) error {
	previous, err := os.ReadFile(filepath.Join(root, ReleaseSurfaceFile))
	if err != nil {
		return err
	}
	current, err := os.ReadFile(filepath.Join(root, SurfaceFile))
	if err != nil {
		return err
	}
	return checkRemovals(root, previous, current)
}

func checkRemovals(root string, previous, current []byte) error {
	ledger, err := retiredDeclarations()
	if err != nil {
		return err
	}
	var failures []error
	missing, err := RemovedWithoutEntry(previous, current, ledger)
	if err != nil {
		return err
	}
	for _, line := range missing {
		failures = append(failures, safeerror.New(line))
	}
	data, err := os.ReadFile(filepath.Join(root, ReleaseLedgerFile))
	if err != nil {
		return err
	}
	for _, line := range LostEntries(data, ledger) {
		failures = append(failures, safeerror.New(line))
	}
	return safeerror.Join("operation failed", failures...)
}
