type testImporter map[string]*types.Package

func (i testImporter) Import(path string) (*types.Package, error) {
	if p := i[path]; p != nil {
		return p, nil
	}
	return nil, fmt.Errorf("unexpected import %s", path)
}

func testAnalysis(t *testing.T, body string) (*Analysis, *ast.File) {
	t.Helper()
	fset := token.NewFileSet()
	imports := testImporter{}
	check := func(path, name, source string, info *types.Info) (*types.Package, *ast.File) {
		file, err := parser.ParseFile(fset, name, source, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		config := types.Config{Importer: imports}
		pkg, err := config.Check(path, fset, []*ast.File{file}, info)
		if err != nil {
			t.Fatal(err)
		}
		imports[path] = pkg
		return pkg, file
	}
	httpPath := frameworkinfo.ModulePath + "/http"
	check(httpPath, "http.go", `package http
 type Endpoint[T any] struct{}
 type Descriptor[T any] struct{}
 type Body[T any] struct{}
 type Response[T any] struct{}
 func DefineRoute() int {return 0}
 func DefineEndpoint[T any](route T) Endpoint[T] {return Endpoint[T]{}}
 func ConfigureEndpoint[T any](e Endpoint[T]) Endpoint[T] {return e}
 func Authenticated[T any](e Endpoint[T]) Endpoint[T] {return e}
 func (e Endpoint[T]) Handle(f func()) {}
 func (e Endpoint[T]) URL() string {return ""}
 func JSONBody[T any](d Descriptor[T]) Body[T] {return Body[T]{}}
 func JSONResponse[T any](status int,d Descriptor[T]) Response[T] {return Response[T]{}}
 func MultipartBody[T any](d Descriptor[T]) Body[T] {return Body[T]{}}
 func MultipartDirectory[T any](d Descriptor[T],directory string) Descriptor[T] {return d}
 `, nil)
	check("example/requests", "request_foundry.gen.go", `// Code generated by foundry generate; DO NOT EDIT.
 package requests
 import "`+httpPath+`"
 type SaveRequest struct{}
 func SaveRequestJSON() http.Descriptor[SaveRequest] {return http.Descriptor[SaveRequest]{}}
 func SaveBody() http.Body[SaveRequest] {return http.JSONBody(SaveRequestJSON())}
 func SaveResponse(status int) http.Response[SaveRequest] {return http.JSONResponse(status,SaveRequestJSON())}
 type MissingRequest struct{}
 func MissingRequestJSON() http.Descriptor[MissingRequest] {return http.Descriptor[MissingRequest]{}}
 type UploadRequest struct{}
 func UploadRequestDescriptor() http.Descriptor[UploadRequest] {return http.Descriptor[UploadRequest]{}}
 func UploadBody(directory string) http.Body[UploadRequest] {return http.MultipartBody(http.MultipartDirectory(UploadRequestDescriptor(),directory))}
 `, nil)
	info := &types.Info{Types: map[ast.Expr]types.TypeAndValue{}, Defs: map[*ast.Ident]types.Object{}, Uses: map[*ast.Ident]types.Object{}, Instances: map[*ast.Ident]types.Instance{}, Selections: map[*ast.SelectorExpr]*types.Selection{}}
	_, file := check("example/routes", "routes.go", body, info)
	a := NewAnalysis(info, fset)
	a.Index(file)
	for _, name := range []string{"SaveRequest", "MissingRequest", "UploadRequest"} {
		a.Declarations["example/requests."+name] = generate.TransportDeclaration{Kind: "dto"}
	}
	return a, file
}
func TestNestedDeclarationsAndAllowedTerminals(t *testing.T) {
	prefix := `package routes; import h "` + frameworkinfo.ModulePath + `/http"; func use(){`
	for _, test := range []struct {
		name, source string
		count        int
	}{
		{"nested", `_=h.DefineEndpoint(h.DefineRoute())`, 1},
		{"generic", `_=h.DefineEndpoint[int](h.DefineRoute())`, 1},
		{"triple", `_=h.ConfigureEndpoint(h.DefineEndpoint(h.DefineRoute()))`, 2},
		{"nested terminal receiver", `h.DefineEndpoint(h.DefineRoute()).Handle(func(){})`, 1},
		{"terminal handle", `r:=h.DefineRoute(); h.DefineEndpoint(r).Handle(func(){})`, 0},
		{"authenticated terminal", `r:=h.DefineRoute();e:=h.DefineEndpoint(r);h.Authenticated(e).Handle(func(){})`, 0},
		{"terminal URL", `r:=h.DefineRoute(); _=h.DefineEndpoint(r).URL()`, 0},
		{"stages", `r:=h.DefineRoute();e:=h.DefineEndpoint(r);e=h.ConfigureEndpoint(e);e.Handle(func(){})`, 0},
		{"conversion", `type Configurer func(h.Endpoint[int]) h.Endpoint[int];r:=h.DefineRoute();e:=h.DefineEndpoint(r);_=Configurer(h.ConfigureEndpoint[int])(h.ConfigureEndpoint(e))`, 1},
		{"converted alias", `type Configurer func(h.Endpoint[int]) h.Endpoint[int];r:=h.DefineRoute();e:=h.DefineEndpoint(r);f:=Configurer(h.ConfigureEndpoint[int]);_=f(h.ConfigureEndpoint(e))`, 1},
		{"alias", `declare:=h.DefineEndpoint[int];_=declare(h.DefineRoute())`, 1},
		{"unrelated name", `DefineEndpoint:=func(int)int{return 0};_=DefineEndpoint(h.DefineRoute())`, 0},
		{"delayed callback", `r:=h.DefineRoute();h.DefineEndpoint(r).Handle(func(){r:=h.DefineRoute();_=h.DefineEndpoint(r)})`, 0},
	} {
		t.Run(test.name, func(t *testing.T) {
			a, f := testAnalysis(t, prefix+test.source+"}")
			got := a.CheckFile(f)
			if len(got) != test.count {
				t.Fatalf("findings=%v, want %d", got, test.count)
			}
			for _, d := range got {
				if d.Position.Line < 1 || !strings.Contains(d.Message, "named local") {
					t.Fatal(d)
				}
			}
		})
	}
}
func TestGeneratedHelpersUseTypedOwner(t *testing.T) {
	source := `package routes
 import h "` + frameworkinfo.ModulePath + `/http"
 import request "example/requests"
 func use(){_=h.JSONBody(request.SaveRequestJSON());_=h.JSONResponse(201,request.SaveRequestJSON());_=request.SaveBody();_=request.SaveResponse(201)}
 `
	a, f := testAnalysis(t, source)
	d := a.CheckFile(f)
	if len(d) != 2 || d[0].Code != "route-helper" || !strings.Contains(d[0].Message, "SaveBody") || !strings.Contains(d[1].Message, "SaveResponse") {
		t.Fatal(d)
	}
}
func TestDotImportedDeclarations(t *testing.T) {
	a, f := testAnalysis(t, `package routes;import . "`+frameworkinfo.ModulePath+`/http";func use(){_=DefineEndpoint(DefineRoute())}`)
	if d := a.CheckFile(f); len(d) != 1 {
		t.Fatal(d)
	}
}

func TestMultipartHelpers(t *testing.T) {
	a, f := testAnalysis(t, `package routes
 import h "`+frameworkinfo.ModulePath+`/http"
 import request "example/requests"
 func use(){
 _=h.MultipartBody(request.UploadRequestDescriptor())
 _=h.MultipartBody(h.MultipartDirectory(request.UploadRequestDescriptor(),"uploads"))
 _=request.UploadBody("uploads")
 }`)
	if d := a.CheckFile(f); len(d) != 2 || !strings.Contains(d[0].Message, "UploadBody") || !strings.Contains(d[1].Message, "UploadBody") {
		t.Fatal(d)
	}
}

