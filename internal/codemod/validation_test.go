// A frozen v0.1 dependency keeps these migration tests meaningful after the
// framework removes the methods. Expected v0.2 output need not type-check.
const oldValidation = `package validation
 type Field[T,V any] struct{}
 type Rule[T any] struct{}
 type Limits struct{}
 func (f Field[T,V]) Rules(...Rule[V]) Rule[T] { return Rule[T]{} }
 func (f Field[T,V]) Validate() error { return nil }
 func (f Field[T,V]) Name() string { return "" }
 func (f Field[T,V]) Select(t T) V { var v V; return v }
 func (f Field[T,V]) WithLabel(string) Field[T,V] { return f }
 func (f Field[T,V]) WithLabelKey(string) Field[T,V] { return f }
 func (r Rule[T]) Validate() error { return nil }
 func (r Rule[T]) Description() (string,error) { return "",nil }
 func (r Rule[T]) Check(ctx int,t T,l Limits) error { return nil }
 func (r Rule[T]) CheckProhibitions(ctx int,t T,l Limits) error { return nil }
 func (r Rule[T]) WithMessage(string) Rule[T] { return r }
`

type testImporter struct{ pkg *types.Package }

func (i testImporter) Import(path string) (*types.Package, error) { return i.pkg, nil }
func rewriteTest(t *testing.T, source, name string) ([]byte, []Entry) {
	t.Helper()
	fset := token.NewFileSet()
	dependency, err := parser.ParseFile(fset, "validation.go", oldValidation, parser.SkipObjectResolution)
	if err != nil {
		t.Fatal(err)
	}
	config := types.Config{}
	pkg, err := config.Check(validationPath, fset, []*ast.File{dependency}, nil)
	if err != nil {
		t.Fatal(err)
	}
	fileName := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(fileName, []byte(source), 0600); err != nil {
		t.Fatal(err)
	}
	file, err := parser.ParseFile(fset, fileName, source, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		t.Fatal(err)
	}
	info := newInfo()
	config.Importer = testImporter{pkg}
	consumer, err := config.Check("consumer", fset, []*ast.File{file}, info)
	if err != nil {
		t.Fatal(err)
	}
	output, entries, err := rewriteFile(fset, file, info, consumer, []RuleSet{Validation{}})
	if err != nil {
		t.Fatal(err)
	}
	return output, entries
}
func TestValidationGolden(t *testing.T) {
	old, err := os.ReadFile("testdata/validation.old.go")
	if err != nil {
		t.Fatal(err)
	}
	expected, err := os.ReadFile("testdata/validation.new.go")
	if err != nil {
		t.Fatal(err)
	}
	expected, err = format.Source(expected)
	if err != nil {
		t.Fatal(err)
	}
	output, entries := rewriteTest(t, string(old), "consumer.go")
	if !bytes.Equal(output, expected) {
		t.Fatalf("got:\n%s\nwant:\n%s", output, expected)
	}
	if len(entries) != 17 {
		t.Fatalf("got %d entries: %+v", len(entries), entries)
	}
	for _, e := range entries {
		if e.Status != Resolved || e.Line < 1 {
			t.Fatalf("unexpected entry: %+v", e)
		}
	}
}
func TestMethodValueCapturesReceiverOnce(t *testing.T) {
	output, entries := rewriteTest(t, `package consumer
 import v "github.com/weiloon1234/Foundry-Go/validation"
 func next() v.Rule[int] { return v.Rule[int]{} }
 var check = next().Check
 var rules = (v.Field[int,string]{}).Rules
 `, "consumer.go")
	if len(entries) != 2 || entries[0].Status != Resolved || entries[1].Status != Resolved {
		t.Fatal(entries)
	}
	if strings.Count(string(output), "next()") != 2 {
		t.Fatalf("receiver duplicated: %s", output)
	}
	file, err := parser.ParseFile(token.NewFileSet(), "new.go", output, 0)
	if err != nil {
		t.Fatal(err)
	}
	var captures, forwardedVariadic int
	ast.Inspect(file, func(n ast.Node) bool {
		if call, ok := n.(*ast.CallExpr); ok {
			if _, ok := call.Fun.(*ast.FuncLit); ok {
				captures++
				if len(call.Args) != 1 {
					t.Fatal("capture must take receiver once")
				}
			}
			if call.Ellipsis.IsValid() {
				forwardedVariadic++
			}
		}
		return true
	})
	if captures != 2 || forwardedVariadic != 1 {
		t.Fatalf("invalid callbacks: %s", output)
	}
}
func TestUnresolvedCases(t *testing.T) {
	for _, body := range []string{
		`func use(r *v.Rule[int]) { _ = r.Validate() }`,
		`type Wrap struct { v.Rule[int] }; func use(r Wrap) { _ = r.Validate() }`,
		`func use(r v.Rule[int]) { v := 1; _ = v; _ = r.Validate() }`,
		`var _ interface{Validate() error} = v.Rule[int]{}`,
		`func use(r v.Rule[int]) interface{Validate() error} { return r }`,
		`func use(r v.Rule[int]) { sink(r) };func sink(interface{Validate() error}) {}`,
	} {
		t.Run(body, func(t *testing.T) {
			source := "package consumer\nimport v \"" + validationPath + "\"\n" + body
			output, entries := rewriteTest(t, source, "consumer.go")
			if len(entries) != 1 || entries[0].Status != Unresolved {
				t.Fatalf("entries: %+v", entries)
			}
			if string(output) != source {
				t.Fatal("unresolved source changed")
			}
		})
	}
}
func TestGeneratedFiles(t *testing.T) {
	for _, tc := range []struct{ name, header string }{{"dto_foundry.gen.go", ""}, {"dto.go", "// Code generated by example. DO NOT EDIT.\n"}} {
		source := tc.header + "package consumer\nimport v \"" + validationPath + "\"\nvar _ = (v.Rule[int]{}).Validate()\n"
		output, entries := rewriteTest(t, source, tc.name)
		if string(output) != source || len(entries) != 1 || entries[0].Status != Regenerate {
			t.Fatalf("generated file changed: %+v", entries)
		}
	}
}
func TestApplyRefusesUnresolvedAndStale(t *testing.T) {
	name := filepath.Join(t.TempDir(), "source.go")
	if err := os.WriteFile(name, []byte("old"), 0640); err != nil {
		t.Fatal(err)
	}
	plan := Plan{Entries: []Entry{{Status: Unresolved}}, Changes: []Change{{name, []byte("old"), []byte("new")}}}
	if _, err := plan.Apply(); err == nil {
		t.Fatal("accepted unresolved plan")
	}
	plan.Entries = nil
	plan.Changes[0].Before = []byte("stale")
	if _, err := plan.Apply(); err == nil {
		t.Fatal("accepted stale plan")
	}
	plan.Changes[0].Before = []byte("old")
	if n, err := plan.Apply(); err != nil || n != 1 {
		t.Fatalf("apply: %d %v", n, err)
	}
	actual, err := os.ReadFile(name)
	if err != nil || string(actual) != "new" {
		t.Fatal(string(actual), err)
	}
	info, err := os.Stat(name)
	if err != nil || info.Mode().Perm() != 0640 {
		t.Fatal("mode changed", err)
	}
}

func TestInterfacesAndDotImports(t *testing.T) {
	// Dot imports require a manual import migration before rewriting.
	source := `package consumer
 import . "github.com/weiloon1234/Foundry-Go/validation"
 var _ = (Rule[int]{}).Validate()
 `
	output, entries := rewriteTest(t, source, "consumer.go")
	if string(output) != source || len(entries) != 1 || entries[0].Status != Unresolved {
		t.Fatal(entries)
	}
	for _, body := range []string{
		`func take[T interface{Validate() error}](v T) {};var _ = take[v.Rule[int]]`,
		`var _ = []interface{Validate() error}{v.Rule[int]{}}`,
		`func send(ch chan interface{Validate() error},r v.Rule[int]) { ch <- r }`,
	} {
		source := "package consumer\nimport v \"" + validationPath + "\"\n" + body
		_, entries := rewriteTest(t, source, "consumer.go")
		if len(entries) != 1 || entries[0].Status != Unresolved {
			t.Fatalf("%s: %+v", body, entries)
		}
	}
}

func TestCallCapturesBeforeArgumentEffects(t *testing.T) {
	output, entries := rewriteTest(t, `package consumer
 import v "github.com/weiloon1234/Foundry-Go/validation"
 var rule v.Rule[int]
 func mutate() int { rule = v.Rule[int]{}; return 1 }
 var _ = rule.Check(mutate(), 1, v.Limits{})
 `, "consumer.go")
	if len(entries) != 1 || entries[0].Status != Resolved {
		t.Fatal(entries)
	}
	file, err := parser.ParseFile(token.NewFileSet(), "new.go", output, 0)
	if err != nil {
		t.Fatal(err)
	}
	found := false
	ast.Inspect(file, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) != 3 {
			return true
		}
		capture, ok := call.Fun.(*ast.CallExpr)
		if !ok {
			return true
		}
		if _, ok := capture.Fun.(*ast.FuncLit); ok && len(capture.Args) == 1 {
			found = true
		}
		return true
	})
	if !found {
		t.Fatalf("receiver not captured before mutation: %s", output)
	}
}
